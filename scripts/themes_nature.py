def _nature_variants(jp: str, en: str,
                     simple_scene: str, easy_scene: str,
                     normal_scene: str, rich_scene: str,
                     simple_title: str, easy_title: str,
                     normal_title: str, rich_title: str,
                     simple_desc: str, easy_desc: str,
                     normal_desc: str, rich_desc: str) -> dict:
    return {
        1: {
            "scenes": {
                "simple": simple_scene,
                "easy":   easy_scene,
                "normal": normal_scene,
                "rich":   rich_scene,
            },
            "titles": {
                "simple": simple_title,
                "easy":   easy_title,
                "normal": normal_title,
                "rich":   rich_title,
            },
            "descs": {
                "simple": simple_desc,
                "easy":   easy_desc,
                "normal": normal_desc,
                "rich":   rich_desc,
            },
        }
    }


