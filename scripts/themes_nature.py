    e_desc  = e_desc  or f"かわいくデフォルメした{jp}の線画。"
    n_desc  = n_desc  or f"{jp}をかわいくデフォルメした線画。"
    r_desc  = r_desc  or f"{jp}が登場するかわいいシーンの線画。"
    return _nature_variants(
        jp, jp,
        s_scene, e_scene, n_scene, r_scene,
        s_title, e_title, n_title, r_title,
        s_desc,  e_desc,  n_desc,  r_desc,
    )


