#!/usr/bin/env python3
"""
columns.ts の業務用語を家庭向けに一括置換。
公的資料の引用名（保育所保育指針 / 幼稚園教育要領）は事実なので保持する。
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
F = ROOT / "src" / "lib" / "columns.ts"

src = F.read_text(encoding="utf-8")

# 引用名を一時マスク（置換対象から保護）
PROTECT = {
    "保育所保育指針": "\x00CITE1\x00",
    "幼稚園教育要領": "\x00CITE2\x00",
}
for k, v in PROTECT.items():
    src = src.replace(k, v)

# 順序重要: 長い・具体的なものから
REPLACEMENTS = [
    # ラベル系
    ("保育士・保護者に役立つ", "子育て中のご家庭に役立つ"),
    ("保育士・保護者の", "子育て中のご家庭の"),
    ("保育のコツ", "おうちでのコツ"),
    ("保育のポイント", "声かけのポイント"),
    ("保育環境", "おうちの環境"),
    ("保育室", "おへや"),
    # 保育現場 系（最頻出）
    ("保育現場で長年子どもたち", "子育ての現場で長年子どもたち"),
    ("保育現場でも家庭でも", "ご家庭でも"),
    ("保育現場でも", "おうちでも"),
    ("保育現場では", "おうちでは"),
    ("保育現場での", "おうちでの"),
    ("保育現場で", "おうちで"),
    ("保育現場の視点", "子育ての視点"),
    ("保育現場の実践", "家庭での実践"),
    ("保育現場", "子育て"),
    # 保育園・幼稚園
    ("保育園・幼稚園で", "ご家庭で"),
    ("保育園・幼稚園の", "ご家庭の"),
    ("保育園・幼稚園", "ご家庭"),
    ("幼稚園で", "ご家庭で"),
    ("幼稚園の", "ご家庭の"),
    ("保育園で", "ご家庭で"),
    ("保育園の", "ご家庭の"),
    ("保育園", "ご家庭"),
    # 保育士
    ("保育士が", "編集部が"),
    ("保育士の", "編集部の"),
    ("保育士", "子育ての専門家"),
    # 制作活動
    ("制作活動アイデア集", "おうち工作アイデア集"),
    ("制作活動", "おうち工作"),
    # 残り「保育」単独（設定保育・保育活動など）
    ("設定保育", "おうち遊び"),
    ("保育活動", "おうち遊び"),
    ("保育・幼児教育の現場", "子育て・幼児教育の場面"),
    ("保育・幼児教育", "子育て・幼児教育"),
    ("保育の現場", "子育ての場面"),
    ("保育", "子育て"),
]

for a, b in REPLACEMENTS:
    src = src.replace(a, b)

# マスク解除
for k, v in PROTECT.items():
    src = src.replace(v, k)

F.write_text(src, encoding="utf-8")

# 残存チェック
remain = re.findall(r"保育(?!所保育指針)", src)
print(f"置換後の残り「保育」(指針以外): {len(remain)}")
print(f"残り「幼稚園」(要領以外):", len(re.findall(r"幼稚園(?!教育要領)", src)))
